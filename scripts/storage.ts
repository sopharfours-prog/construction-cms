import "./load-env";

import { createWriteStream } from "node:fs";
import { mkdir, readdir, readFile, stat } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";

import {
  CreateBucketCommand,
  GetObjectCommand,
  HeadBucketCommand,
  ListObjectsV2Command,
  PutBucketPolicyCommand,
  PutObjectCommand,
  S3Client,
} from "@aws-sdk/client-s3";

/**
 * Object-storage maintenance for STORAGE_DRIVER=s3 (MinIO, AWS S3, Cloudflare R2),
 * using the same S3_* variables as the app:
 *
 *   npx tsx scripts/storage.ts init            create the bucket; public/ readable by anyone
 *   npx tsx scripts/storage.ts export <dir>    copy every object into <dir> (backup)
 *   npx tsx scripts/storage.ts import <dir>    upload <dir> back into the bucket (restore)
 *
 * In the Docker deployment these run in the tools image; see DEPLOYMENT.md.
 */
const MIME_BY_EXT: Record<string, string> = {
  jpg: "image/jpeg",
  png: "image/png",
  webp: "image/webp",
  avif: "image/avif",
  mp4: "video/mp4",
  webm: "video/webm",
  pdf: "application/pdf",
  docx: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  xlsx: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
};
/** Shown in the browser; everything else downloads (same rule as the app's uploads). */
const INLINE = new Set(["jpg", "png", "webp", "avif", "mp4", "webm", "pdf"]);

function required(name: string): string {
  const value = process.env[name];
  if (!value) throw new Error(`${name} is not set`);
  return value;
}

let bucket: string;
let client: S3Client;

/** Read lazily, so a missing variable is reported as one clear line by main(). */
function connect() {
  bucket = required("S3_BUCKET");
  client = new S3Client({
    region: process.env.S3_REGION || "auto",
    endpoint: process.env.S3_ENDPOINT || undefined,
    forcePathStyle: process.env.S3_FORCE_PATH_STYLE === "true",
    credentials: {
      accessKeyId: required("S3_ACCESS_KEY"),
      secretAccessKey: required("S3_SECRET_KEY"),
    },
  });
}

async function init() {
  const exists = await client.send(new HeadBucketCommand({ Bucket: bucket })).then(
    () => true,
    () => false,
  );
  if (!exists) await client.send(new CreateBucketCommand({ Bucket: bucket }));
  // Only public/ is world-readable; private/ (customer attachments) stays closed.
  await client.send(
    new PutBucketPolicyCommand({
      Bucket: bucket,
      Policy: JSON.stringify({
        Version: "2012-10-17",
        Statement: [
          {
            Effect: "Allow",
            Principal: { AWS: ["*"] },
            Action: ["s3:GetObject"],
            Resource: [`arn:aws:s3:::${bucket}/public/*`],
          },
        ],
      }),
    }),
  );
  console.log(`bucket ${bucket} ready: public/ readable, private/ not`);
}

async function listKeys(): Promise<string[]> {
  const keys: string[] = [];
  let token: string | undefined;
  do {
    const page = await client.send(
      new ListObjectsV2Command({ Bucket: bucket, ContinuationToken: token }),
    );
    for (const object of page.Contents ?? []) if (object.Key) keys.push(object.Key);
    token = page.IsTruncated ? page.NextContinuationToken : undefined;
  } while (token);
  return keys;
}

/** Keys are generated by the app (no "..", no absolute paths); checked anyway before touching disk. */
function localPath(root: string, key: string): string {
  const full = path.resolve(root, key);
  if (!full.startsWith(path.resolve(root) + path.sep)) throw new Error(`Unsafe object key: ${key}`);
  return full;
}

async function exportTo(directory: string) {
  const keys = await listKeys();
  for (const key of keys) {
    const file = localPath(directory, key);
    await mkdir(path.dirname(file), { recursive: true });
    const object = await client.send(new GetObjectCommand({ Bucket: bucket, Key: key }));
    if (!object.Body) throw new Error(`Empty response for ${key}`);
    await pipeline(object.Body as Readable, createWriteStream(file));
  }
  console.log(`exported ${keys.length} files from ${bucket} to ${directory}`);
}

async function importFrom(directory: string) {
  const root = path.resolve(directory);
  if (!(await stat(root).catch(() => null))?.isDirectory())
    throw new Error(`Not a directory: ${directory}`);
  const entries = await readdir(root, { recursive: true, withFileTypes: true });
  let count = 0;
  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const file = path.join(entry.parentPath, entry.name);
    const key = path.relative(root, file).split(path.sep).join("/");
    const ext = path.extname(key).slice(1).toLowerCase();
    await client.send(
      new PutObjectCommand({
        Bucket: bucket,
        Key: key,
        Body: await readFile(file),
        ContentType: MIME_BY_EXT[ext] ?? "application/octet-stream",
        ContentDisposition: INLINE.has(ext) ? "inline" : "attachment",
        CacheControl: key.startsWith("public/")
          ? "public, max-age=31536000, immutable"
          : "private, no-store",
      }),
    );
    count++;
  }
  console.log(`imported ${count} files from ${directory} into ${bucket}`);
}

async function main() {
  const [command, directory] = process.argv.slice(2);
  const known = command === "init" || ((command === "export" || command === "import") && directory);
  if (!known) throw new Error("Usage: tsx scripts/storage.ts init | export <dir> | import <dir>");
  connect();
  if (command === "init") return init();
  if (command === "export" && directory) return exportTo(directory);
  if (command === "import" && directory) return importFrom(directory);
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
